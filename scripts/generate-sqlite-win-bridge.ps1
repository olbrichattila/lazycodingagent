# Win32 wrappers - use full signatures for common ones, generic for GetSystemInfo
[void]$sb.AppendLine('// --- Win32 public-name forwarders ---')

function Append-WinForwarder {
  param([string]$Name)
  $esc = $Name.Replace('''', '''''')
  switch ($Name) {
    'CreateFileW' {
      [void]$sb.AppendLine("function LcaWin_$Name(lpFileName: PWideChar; dwDesiredAccess, dwShareMode: DWORD; lpSecurity: Pointer; dwCreationDisposition, dwFlagsAndAttributes: DWORD; hTemplateFile: THandle): THandle; stdcall; public name '$esc';")
      [void]$sb.AppendLine("begin Result := Windows.$Name(lpFileName, dwDesiredAccess, dwShareMode, lpSecurity, dwCreationDisposition, dwFlagsAndAttributes, hTemplateFile); end;")
    }
    'CloseHandle' {
      [void]$sb.AppendLine("function LcaWin_$Name(hObject: THandle): BOOL; stdcall; public name '$esc';")
      [void]$sb.AppendLine("begin Result := Windows.$Name(hObject); end;")
    }
    'Sleep' {
      [void]$sb.AppendLine("procedure LcaWin_$Name(dwMilliseconds: DWORD); stdcall; public name '$esc';")
      [void]$sb.AppendLine("begin Windows.$Name(dwMilliseconds); end;")
    }
    'GetSystemInfo' {
      [void]$sb.AppendLine("procedure LcaWin_$Name(lpSystemInfo: PSystemInfo); stdcall; public name '$esc';")
      [void]$sb.AppendLine("begin Windows.$Name(lpSystemInfo); end;")
    }
    'GetSystemTime' {
      [void]$sb.AppendLine("procedure LcaWin_$Name(var lpSystemTime: TSystemTime); stdcall; public name '$esc';")
      [void]$sb.AppendLine("begin Windows.$Name(lpSystemTime); end;")
    }
    'GetSystemTimeAsFileTime' {
      [void]$sb.AppendLine("procedure LcaWin_$Name(var lpFileTime: TFileTime); stdcall; public name '$esc';")
      [void]$sb.AppendLine("begin Windows.$Name(lpFileTime); end;")
    }
    'OutputDebugStringA' {
      [void]$sb.AppendLine("procedure LcaWin_$Name(lpOutputString: PAnsiChar); stdcall; public name '$esc';")
      [void]$sb.AppendLine("begin Windows.$Name(lpOutputString); end;")
    }
    'OutputDebugStringW' {
      [void]$sb.AppendLine("procedure LcaWin_$Name(lpOutputString: PWideChar); stdcall; public name '$esc';")
      [void]$sb.AppendLine("begin Windows.$Name(lpOutputString); end;")
    }
    default {
      # Fallback: alias to Windows with same name (works for many stdcall APIs)
      if ($winApi.Contains($Name)) {
        $ret = $winApi[$Name]
        if ($ret -eq 'procedure') {
          [void]$sb.AppendLine("procedure LcaWin_$Name(...); stdcall; public name '$esc';")
          [void]$sb.AppendLine("begin Windows.$Name(...); end;")
        } else {
          [void]$sb.AppendLine("function LcaWin_$Name(...): $ret; stdcall; public name '$esc';")
          [void]$sb.AppendLine("begin Result := Windows.$Name(...); end;")
        }
      }
    }
  }
}

foreach ($name in $winApi.Keys) {
  if ($symbols -contains $name) {
    Append-WinForwarder -Name $name
  }
}

# CRT wrapper implementations (varargs forward to typed import)
foreach ($fn in $crtApi) {
  if ($symbols -notcontains $fn) { continue }
  $wrap = "LcaWrap_$fn"
  $pasFn = "LcaCrt_$fn"
  [void]$sb.AppendLine("function $wrap(...): Pointer; cdecl; public name '$($fn.Replace("'","''"))';")
  [void]$sb.AppendLine("begin Result := Pointer($pasFn(...)); end;")
}

# Critical section imports via kernel32
foreach ($sym in @(
    'InitializeCriticalSection', 'EnterCriticalSection', 'LeaveCriticalSection',
    'DeleteCriticalSection', 'TryEnterCriticalSection'
  )) {
  if ($symbols -notcontains "__imp_$sym") { continue }
  $esc = $sym.Replace('''', '''''')
  [void]$sb.AppendLine("procedure LcaWin_$sym(var lpCriticalSection: TRTLCriticalSection); stdcall; public name '$esc';")
  [void]$sb.AppendLine("begin Windows.$sym(lpCriticalSection); end;")
}
if ($symbols -contains '__imp_RaiseException') {
  [void]$sb.AppendLine('procedure LcaWin_RaiseException(dwExceptionCode, dwExceptionFlags: DWORD; nNumberOfArguments: DWORD; lpArguments: PULONG); stdcall; public name ''RaiseException'';')
  [void]$sb.AppendLine('begin Windows.RaiseException(dwExceptionCode, dwExceptionFlags, nNumberOfArguments, lpArguments); end;')
}
if ($symbols -contains '__imp_GetCurrentThreadId') {
  [void]$sb.AppendLine('function LcaWin_GetCurrentThreadId: DWORD; stdcall; public name ''GetCurrentThreadId'';')
  [void]$sb.AppendLine('begin Result := Windows.GetCurrentThreadId; end;')
}

