  if ($fn -match '^_') {
    $extName = $fn
  } else {
    $extName = $fn
  }
  $pasFn = "LcaCrt_$fn"
  [void]$sb.AppendLine("function $pasFn")
  if ($fn -eq 'malloc') {
    [void]$sb.AppendLine('  (size: size_t): Pointer; cdecl; external ''ucrtbase.dll'' name ''malloc'';')
  } elseif ($fn -eq 'free') {
    [void]$sb.AppendLine('  (ptr: Pointer): void; cdecl; external ''ucrtbase.dll'' name ''free'';')
  } elseif ($fn -eq 'realloc') {
    [void]$sb.AppendLine('  (ptr: Pointer; size: size_t): Pointer; cdecl; external ''ucrtbase.dll'' name ''realloc'';')
  } elseif ($fn -eq 'log') {
    [void]$sb.AppendLine('  (x: Double): Double; cdecl; external ''ucrtbase.dll'' name ''log'';')
  } elseif ($fn -eq '_msize') {
    [void]$sb.AppendLine('  (ptr: Pointer): size_t; cdecl; external ''ucrtbase.dll'' name ''_msize'';')
  } elseif ($fn -eq '_localtime64_s') {
    [void]$sb.AppendLine('  (tm: Pointer; time64: Int64): errno_t; cdecl; external ''ucrtbase.dll'' name ''_localtime64_s'';')
  } elseif ($fn -eq '_beginthreadex') {
    [void]$sb.AppendLine('  (security: Pointer; stack: Cardinal; func: Pointer; arg: Pointer; flags: Cardinal; id: PCardinal): Cardinal; cdecl; external ''ucrtbase.dll'' name ''_beginthreadex'';')
  } elseif ($fn -eq '_endthreadex') {
    [void]$sb.AppendLine('  (code: Cardinal): void; cdecl; external ''ucrtbase.dll'' name ''_endthreadex'';')
  } elseif ($fn -match '^mem') {
    [void]$sb.AppendLine("  (...): Pointer; cdecl; external 'ucrtbase.dll' name '$extName';")
  } elseif ($fn -match '^str') {
    [void]$sb.AppendLine("  (...): Pointer; cdecl; external 'ucrtbase.dll' name '$extName';")
  } else {
    [void]$sb.AppendLine("  (...): Pointer; cdecl; external 'ucrtbase.dll' name '$extName';")
  }
