# Generate uSqliteWinEmbedBridge.pas — MSVC sqlite3_embed.o undefineds for FPC internal linker.
param(
  [string]$EmbedObj = '',
  [string]$OutUnit = ''
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
if (-not $EmbedObj) {
  $EmbedObj = Join-Path $Root 'packages\LazySqliteStatic\src\sqlite3_embed.o'
}
if (-not $OutUnit) {
  $OutUnit = Join-Path $Root 'packages\LazySqliteStatic\src\uSqliteWinEmbedBridge.pas'
}

function Resolve-Nm {
  $candidates = @(
    'C:\Program Files\Git\usr\bin\nm.exe'
  )
  $winGetRoot = Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Packages'
  if (Test-Path -LiteralPath $winGetRoot -PathType Container) {
    foreach ($pkg in Get-ChildItem -Path $winGetRoot -Filter 'BrechtSanders.WinLibs*' -Directory -ErrorAction SilentlyContinue) {
      $candidates += Join-Path $pkg.FullName 'mingw64\bin\nm.exe'
    }
  }
  $cmd = Get-Command nm -ErrorAction SilentlyContinue
  if ($cmd -and $cmd.Source -notmatch '\\fpc\\') {
    $candidates += $cmd.Source
  }
  foreach ($path in ($candidates | Select-Object -Unique)) {
    if (Test-Path -LiteralPath $path -PathType Leaf) {
      return $path
    }
  }
  throw 'generate-sqlite-win-bridge: nm not found (Git usr bin or WinLibs mingw64)'
}

if (-not (Test-Path -LiteralPath $EmbedObj -PathType Leaf)) {
  throw "generate-sqlite-win-bridge: missing embed object $EmbedObj"
}

$nm = Resolve-Nm
$undefLines = & $nm -u $EmbedObj 2>&1
$symbols = @()
foreach ($line in $undefLines) {
  if ($line -match '^\s*U\s+(\S+)') {
    $symbols += $Matches[1]
  }
}
if ($symbols.Count -eq 0) {
  throw "generate-sqlite-win-bridge: no undefined symbols in $EmbedObj"
}

