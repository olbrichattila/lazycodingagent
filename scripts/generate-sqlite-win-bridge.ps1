foreach ($sym in $symbols) {
  if ($sym -like '__imp_*') {
    $base = $sym.Substring(6) # after __imp_
    if ($base -like '_*') {
      $target = "LcaWrap_$base"
    } elseif ($winApi.Contains($base)) {
      $target = "LcaWin_$base"
    } else {
      $target = "LcaWin_$base"
    }
    [void]$sb.AppendLine("  $sym := Pointer(@$target);")
  }
}

